"""Regression tests for the Trailhead `report` subcommand and report module.

The renderer and CLI writer are covered deterministically offline (no network):
the live ``execute_search`` and ``extract_hits`` steps are monkeypatched so the
report contract — coverage table, notable sources, caveats, and a written .md file —
is stable regardless of public-search availability.
"""
from __future__ import annotations

import json

from hermes_trailhead.cli import main
from hermes_trailhead.report import (
    Report,
    LaneCoverage,
    NotableSource,
    default_title,
    humanize,
    render_markdown,
    run_report,
    slugify,
    write_report,
)
from hermes_trailhead.extract import ExtractedHit, ExtractionResult
from hermes_trailhead.search import (
    ExecutedSearchRun,
    SearchAction,
    SearchExecution,
    SearchHit,
    SearchRun,
)


def _fake_executed():
    action = SearchAction(
        platform="web",
        status="ready",
        query="test query",
        recommended_tool="hermes-trailhead --execute",
        caveat="Use web_extract on promising URLs; search results are leads, not evidence.",
    )
    plan = SearchRun(
        query="test query",
        platform="all",
        mode="hermes_trailhead_action_plan",
        paid_api_required=False,
        actions=(action,),
    )
    hits = (SearchHit(title="Prusa KB — PLA", url="https://help.prusa3d.com/article/pla_2062", snippet="PLA is easy"),)
    execution = SearchExecution(
        platform="web",
        status="ok",
        query="test query",
        executed_query="test query",
        engine="jina_duckduckgo",
        result_count=1,
        hits=hits,
        action_status="ready",
        approval_required=False,
        evidence_state="search_hits",
        caveat="Use web_extract on promising URLs; search results are leads, not evidence.",
    )
    return ExecutedSearchRun(plan=plan, executions=(execution,))


def _fake_extract(hits, limit, timeout):
    out = []
    for hit in hits[:limit]:
        content = "PLA is easy to print and low warping. " * 4
        out.append(
            ExtractedHit(
                title=hit.title,
                url=hit.url,
                snippet=hit.snippet,
                extraction=ExtractionResult(status="ok", content=content, content_length=len(content)),
            )
        )
    return out


def test_slugify_and_humanize():
    assert slugify("Open Source Bounty Market, 2026!") == ("open-source-bounty-market-2026")
    assert humanize("open-source-bounty-market-2026") == "Open Source Bounty Market 2026"
    assert default_title("open-source-bounty-market") == "Open Source Bounty Market — Trailhead Research Report"
    assert slugify("!!!" ) == "report"


def test_render_markdown_structure():
    report = Report(
        title="Open Source Bounty Market — Trailhead Research Report",
        slug="open-source-bounty-market",
        query="open source bounty market reality",
        generated_at="2026-09-17",
        coverage=(
            LaneCoverage(platform="web", status="ok", engine="jina_duckduckgo", hit_count=3, extracted_count=2),
            LaneCoverage(platform="github", status="ok", engine="searxng_site_github", hit_count=1, extracted_count=1),
        ),
        notable=(
            NotableSource(
                platform="web",
                title="The 2026 Open Source Money Map",
                url="https://example.com/money-map",
                score=40,
                summary="The 2026 Open Source Money Map: How Developers Actually Get Paid — AgentUpdate.ai",
            ),
        ),
        caveats=(
            "Use web_extract on promising URLs; search results are leads, not evidence.",
            "No dedicated TikTok reader is configured by default.",
        ),
    )

    md = render_markdown(report)

    assert md.startswith("# Open Source Bounty Market — Trailhead Research Report")
    assert "*Generated by Hermes Trailhead, 2026-09-17" in md
    assert "## Query" in md and "`open source bounty market reality`" in md
    assert "## Coverage" in md
    assert "| Lane | Status | Engine | Hits | Extracted |" in md
    assert "| web | ok | jina_duckduckgo | 3 | 2 |" in md
    assert "| github | ok | searxng_site_github | 1 | 1 |" in md
    assert "## Notable extracted sources" in md
    assert "| web | The 2026 Open Source Money Map | 40 |" in md
    assert "## Caveats (honest blind spots)" in md
    assert "- Use web_extract on promising URLs; search results are leads, not evidence." in md
    assert "search all --execute --extract" in md
    assert "Evidence output of Trailhead `search all --execute --extract`." in md


def test_render_markdown_escapes_pipes_in_cells():
    report = Report(
        title="T",
        slug="s",
        query="q",
        generated_at="2026-09-17",
        coverage=(),
        notable=(
            NotableSource(
                platform="web",
                title="Curly|Title",
                url="https://example.com/x",
                score=10,
                summary="A summary | with a pipe",
            ),
        ),
        caveats=(),
    )
    md = render_markdown(report)
    assert "Curly\\|Title" in md
    assert "A summary \\| with a pipe" in md


def test_run_report_offline(monkeypatch):
    from hermes_trailhead import report as report_mod

    monkeypatch.setattr(report_mod, "execute_search", lambda platform, query, limit, fetch: _fake_executed())
    monkeypatch.setattr(report_mod, "extract_hits", _fake_extract)

    rep = run_report("test query")
    assert rep.slug == "test-query"
    assert rep.title == "Test Query — Trailhead Research Report"
    assert rep.query == "test query"
    assert len(rep.coverage) == 1
    assert rep.coverage[0].platform == "web"
    assert rep.coverage[0].extracted_count == 1
    assert len(rep.notable) == 1
    assert rep.notable[0].title == "Prusa KB — PLA"
    assert len(rep.caveats) == 1


def test_write_report_writes_file(tmp_path):
    report = Report(
        title="T",
        slug="test-query",
        query="test query",
        generated_at="2026-09-17",
        coverage=(),
        notable=(),
        caveats=(),
    )
    path = write_report(report, str(tmp_path))
    assert path.endswith("deliverable-test-query.md")
    assert tmp_path.joinpath("deliverable-test-query.md").exists()
    assert "test query" in tmp_path.joinpath("deliverable-test-query.md").read_text()


def test_report_cli_writes_file_and_emits_path(monkeypatch, capsys, tmp_path):
    from hermes_trailhead import report as report_mod

    monkeypatch.setattr(report_mod, "execute_search", lambda platform, query, limit, fetch: _fake_executed())
    monkeypatch.setattr(report_mod, "extract_hits", _fake_extract)

    rc = main(["report", "test query", "--out", str(tmp_path), "--format", "json"])
    out = capsys.readouterr().out

    assert rc == 0
    data = json.loads(out)
    assert data["slug"] == "test-query"
    assert data["path"].endswith("deliverable-test-query.md")
    assert tmp_path.joinpath("deliverable-test-query.md").exists()
    assert data["coverage"][0]["platform"] == "web"
    assert data["notable_count"] == 1


